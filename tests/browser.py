"""Localhost preview tests. Start npm start first. No public deployment."""
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from playwright.sync_api import sync_playwright

root=Path(__file__).resolve().parents[1]
artifacts=Path(os.environ.get('BUG_ARTIFACT_DIR',str(root/'artifacts')))
artifacts.mkdir(parents=True,exist_ok=True)
base_url=os.environ.get('BUG_BASE_URL','http://127.0.0.1:4173').rstrip('/')
url=base_url+'/BUG_Game.html'
with sync_playwright() as p:
    executable=os.environ.get('BUG_CHROMIUM_PATH') or ('/usr/bin/chromium' if Path('/usr/bin/chromium').exists() else None)
    browser=p.chromium.launch(executable_path=executable,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True)
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda msg:errors.append(msg.text) if msg.type=='error' else None)
    page.goto(url)
    assert page.get_by_role('button',name='開始遊戲 · 新旅程').is_visible()
    assert page.locator('style').evaluate('(s)=>s.sheet.cssRules.length')>100
    assert page.locator('#continue').is_hidden()
    page.screenshot(path=str(artifacts/'mobile-start.png'),full_page=True)
    page.get_by_role('button',name='開始遊戲 · 新旅程').click()
    page.get_by_role('button',name='固定示範：首爾麻浦區').click()
    assert '韓國・首爾麻浦區' in page.locator('#character').inner_text()
    assert '法國・巴黎第11區' in page.locator('#character').inner_text()
    page.get_by_role('button',name='重新抽選出生地').click()
    assert '法國・巴黎第11區' in page.locator('#character').inner_text()
    page.get_by_role('button',name='固定示範：首爾麻浦區').click()
    page.get_by_role('button',name='進入巴黎 · 2026-11-01').click()
    assert '08:17' in page.locator('#story').inner_text()
    page.get_by_role('button',name='◎ 全球觀測').click()
    assert '鎖定' in page.locator('#city-tokyo').inner_text()
    assert '鎖定' in page.locator('#city-new-york').inner_text()
    assert '私人訊息' not in page.locator('#city-seoul').inner_text()
    for button in page.locator('#world button').all():
        box=button.bounding_box()
        assert box['width']>=44 and box['height']>=44
    page.get_by_role('button',name='✦ 劇情').click()
    page.locator('[data-choice="verify-video"]').click()
    assert '08:29' in page.locator('#story').inner_text()
    assert '先前比對' in page.locator('#story').inner_text()
    page.reload()
    assert page.get_by_role('button',name='繼續本機進度').is_visible()
    page.get_by_role('button',name='繼續本機進度').click()
    assert '08:29' in page.locator('#story').inner_text()
    page.locator('[data-choice="trace-source"]').click()
    assert '08:41' in page.locator('#story').inner_text()
    assert page.locator('[data-choice="compare-window"]').is_enabled()
    page.screenshot(path=str(artifacts/'mobile-story.png'),full_page=True)
    page.get_by_role('button',name='☷ 訊息紀錄').click()
    assert '兩個時間戳' in page.locator('#records').inner_text()
    assert '聲稱時間' in page.locator('#records').inner_text()
    assert '可信狀態' in page.locator('#records').inner_text()
    assert '原始上傳者還找不到' not in page.locator('#records').inner_text()
    page.get_by_role('button',name='◎ 全球觀測').click()
    assert '鎖定' not in page.locator('#city-tokyo').inner_text()
    page.get_by_role('button',name='查看東京').click()
    assert 'selected' in page.locator('#city-tokyo').get_attribute('class')
    page.screenshot(path=str(artifacts/'mobile-world.png'),full_page=True)
    page.get_by_role('button',name='✦ 劇情').click()
    page.locator('[data-choice="compare-window"]').click()
    assert '謹慎的比對者' in page.locator('#story').inner_text()
    page.screenshot(path=str(artifacts/'mobile-ending.png'),full_page=True)
    for width in [320,375,390,430,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        for tab in ['✦ 劇情','☷ 訊息紀錄','◎ 全球觀測']:
            page.get_by_role('button',name=tab).click()
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),(width,tab)
    page.get_by_label('CRT 掃描線').check()
    assert 'crt' in page.locator('body').get_attribute('class')
    page.get_by_label('CRT 掃描線').uncheck()
    page.get_by_role('button',name='重設進度 ↺').click()
    page.get_by_role('button',name='保留旅程',exact=True).click()
    assert '韓國・首爾麻浦區' in page.locator('#character').inner_text()
    page.get_by_role('button',name='重設進度 ↺').click()
    page.get_by_role('button',name='確認重設進度').click()
    assert page.locator('#continue').is_hidden()
    page.reload()
    assert page.locator('#continue').is_hidden()
    page.get_by_role('button',name='開始遊戲 · 新旅程').click()
    page.get_by_role('button',name='進入巴黎 · 2026-11-01').click()
    page.locator('[data-choice="share-video"]').click()
    page.locator('[data-choice="wait-window"]').click()
    assert page.locator('[data-choice="compare-window"]').is_disabled()
    page.locator('[data-choice="spread-theory"]').click()
    assert '推測擴散者' in page.locator('#story').inner_text()
    page.get_by_role('button',name='回顧訊息與選擇').click()
    assert '更多帳號轉傳' in page.locator('#records').inner_text()
    assert '兩個時間戳' not in page.locator('#records').inner_text()
    # New-game replacement has an explicit confirmation.
    page.get_by_role('button',name='← 返回首頁（保留進度）').click()
    page.get_by_role('button',name='開始遊戲 · 新旅程').click()
    page.get_by_role('button',name='保留目前進度').click()
    assert page.get_by_role('button',name='繼續本機進度').is_visible()
    # Keyboard activation, reduced motion and corrupt-save handling.
    page.emulate_media(reduced_motion='reduce')
    page.get_by_role('button',name='繼續本機進度').focus()
    page.keyboard.press('Enter')
    assert page.locator('#play').is_visible()
    page.evaluate("localStorage.setItem('moth-effect-bug-v2','{bad')")
    page.reload()
    assert '損毀' in page.locator('#save-status').inner_text()
    assert page.locator('#continue').is_hidden()
    blocked=browser.new_context()
    blocked.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked')}})")
    q=blocked.new_page()
    q.goto(url)
    q.get_by_role('button',name='開始遊戲 · 新旅程').click()
    q.get_by_role('button',name='進入巴黎 · 2026-11-01').click()
    assert '無法存檔' in q.locator('#save-status').inner_text()
    assert q.locator('[data-choice]').count()==3
    assert not errors,errors
    report={'result':'PASS','browser':browser.version,'mode':'automated mobile Chromium emulation','tested_url':url,'recorded_at':datetime.now(timezone.utc).isoformat(),'checks':['homepage','demo draw and fixed route','distinct residence','0817/0829/0841 nodes','two distinct branches','gated choices','no premature city facts','message provenance','save reload','reset cancel/confirm','new game confirmation','320–1440px no overflow across all tabs','44px map targets','keyboard Enter','CRT toggle','reduced motion','corrupt save','blocked storage','CSSOM parsed','no console/page errors'],'external_device_verified':False}
    (artifacts/'browser-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
    print(json.dumps(report,ensure_ascii=False))
    browser.close()
